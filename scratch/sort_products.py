        # Because we replaced * Código: with * PLU:
        match = re.search(r'\* PLU: \s*(\d+)\s*\|\s*(.*)', line)
        if match:
            code = match.group(1).strip()
            desc = match.group(2).strip()
            # if the desc still has a cod interno at the end, we can ignore it for sorting or strip it
