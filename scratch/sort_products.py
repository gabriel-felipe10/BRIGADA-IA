for line in text.splitlines():
    line = line.strip()
    if line.startswith("* Código:"):
        # Remove (Cód. Interno: não informado)
        line = line.replace(" (Cód. Interno: não informado)", "")
        
        # Replace * Código: with * PLU:
        line = line.replace("* Código:", "* PLU:")
        
